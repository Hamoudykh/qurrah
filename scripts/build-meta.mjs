#!/usr/bin/env node
// Regenerates js/data/meta.js from the Quran.com API:
//   * chapter metadata (names, verse counts, revelation place)
//   * word / letter counts for every catalog item (used to justify the levels)
// No ayah text is written to disk — only names and counts.
//
// Usage:  node scripts/build-meta.mjs
// (Behind an HTTPS proxy on Node 22, run with NODE_USE_ENV_PROXY=1.)

import { writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import { CATALOG, levelFor } from '../js/data/catalog.js';

const API = 'https://api.quran.com/api/v4';
const root = join(dirname(fileURLToPath(import.meta.url)), '..');
// Arabic letters (incl. alef wasla) — waqf signs and diacritics are not letters.
const LETTER = /[\u0621-\u064A\u0671\u06CC\u06C1\u06D2]/g;

async function get(url, tries = 4) {
  for (let i = 0; i < tries; i++) {
    try {
      const r = await fetch(url, { headers: { accept: 'application/json' } });
      if (r.ok) return r.json();
      throw new Error(`HTTP ${r.status}`);
    } catch (e) {
      if (i === tries - 1) throw new Error(`${url}: ${e.message}`);
      await new Promise((res) => setTimeout(res, 1000 * 2 ** i));
    }
  }
}

async function versesOf(surah, from, to) {
  const out = [];
  let page = 1;
  for (;;) {
    let url = `${API}/verses/by_chapter/${surah}?fields=text_uthmani&per_page=50&page=${page}`;
    if (from) url += `&from=${from}&to=${to}`;
    const d = await get(url);
    out.push(...d.verses);
    if (from || !d.pagination.next_page) break;
    page++;
  }
  return from ? out.filter((v) => v.verse_number >= from && v.verse_number <= to) : out;
}

function stats(verses) {
  let words = 0, letters = 0, longestAyahWords = 0;
  for (const v of verses) {
    const toks = v.text_uthmani.trim().split(/\s+/).filter((t) => /[\u0621-\u064A\u0671]/.test(t));
    words += toks.length;
    longestAyahWords = Math.max(longestAyahWords, toks.length);
    letters += (v.text_uthmani.match(LETTER) || []).length;
  }
  return { ayahs: verses.length, words, letters, longestAyahWords };
}

const chapters = (await get(`${API}/chapters?language=en`)).chapters.map((c) => ({
  id: c.id,
  nameSimple: c.name_simple,
  nameArabic: c.name_arabic,
  meaningEn: c.translated_name?.name || '',
  verses: c.verses_count,
  place: c.revelation_place,
  bismillahPre: c.bismillah_pre,
}));

const counts = {};
const mismatches = [];
for (const item of CATALOG) {
  const vs = item.type === 'surah' ? await versesOf(item.surah) : await versesOf(item.surah, item.from, item.to);
  counts[item.id] = stats(vs);
  if (item.level !== 'foundation') {
    const expected = levelFor(counts[item.id]);
    if (expected !== item.level) mismatches.push(`${item.id}: catalog=${item.level} rule=${expected}`);
  }
  process.stdout.write('.');
}
process.stdout.write('\n');

const banner = `// GENERATED by scripts/build-meta.mjs on ${new Date().toISOString().slice(0, 10)} from ${API}.
// Contains chapter names/counts and word counts only — no ayah text. Do not edit by hand.
`;
const body = `${banner}
export const META_SOURCE = ${JSON.stringify({ api: API, generated: new Date().toISOString() })};
export const CHAPTERS = ${JSON.stringify(chapters)};
export const COUNTS = ${JSON.stringify(counts, null, 0)};
`;
await writeFile(join(root, 'js/data/meta.js'), body);
console.log(`wrote js/data/meta.js (${chapters.length} chapters, ${Object.keys(counts).length} items)`);
if (mismatches.length) {
  console.warn('Level rule mismatches:\n  ' + mismatches.join('\n  '));
  process.exitCode = 1;
}
